import { describe, expect, it } from "vitest";

import { normalizePartyName } from "@/lib/documents/party-name";

describe("normalizePartyName", () => {
  it.each([
    ['ТОВАРИСТВО З ОБМЕЖЕНОЮ ВІДПОВІДАЛЬНІСТЮ "ДЕМО-ПРЕС"', '"ДЕМО-ПРЕС"'],
    ['Товаристо з обмеженою відповідальністю "Видавництво "Демо"', '"Демо"'],
    ['ПРИВАТНЕ ПІДПРИЄМСТВО "ТЕСТОВА ДРУКАРНЯ"', '"ТЕСТОВА ДРУКАРНЯ"'],
    ['"ВИДАВНИЧИЙ ДІМ "ТЕСТОВИЙ ВИБІР"', '"ТЕСТОВИЙ ВИБІР"'],
    ['Товариство з обмеженою відповідальністю "Видавництво"Демо"', '"Демо"'],
    ["«Видавництво«Демо»", "«Демо»"],
    ["Видавництвомісто", "Видавництвомісто"],
  ])("returns %s as %s", (input, expected) => {
    expect(normalizePartyName(input)).toBe(expected);
  });
});
